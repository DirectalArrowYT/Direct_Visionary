"""13.0.5 counterparts of the 13.0.4 main offsets slight_replica uses -> src/slight/ver_table.rs"""
import re, sys, glob
sys.path.insert(0, r'D:/Documents/Hype Bros Studios/tools/recomp_editor')
import port_13_0_5 as P
src, out = sys.argv[1], sys.argv[2]
B = r'D:/Documents/ssbu-recomp/build/binaries/'
t4, t5 = P.text(B + '13.0.4/main.elf'), P.text(B + '13.0.5/main.elf')
offs = set()
pats = [r'from_offset\((0x[0-9a-fA-F_]+)\)', r'offset\s*=\s*(0x[0-9a-fA-F_]+)', r'text_base\(\)\s*\+\s*(0x[0-9a-fA-F_]+)',
        r'\btext\s*\+\s*(0x[0-9a-fA-F_]+)', r'_OFFSET: usize = (0x[0-9a-fA-F_]+)', r'^\s*\((?:0x[0-9a-f]+usize|0x[0-9a-f]+), 0x[0-9a-f]+(?:usize)?, (0x[0-9a-f]+)\)',
        r'^\s*\((0x[0-9a-f]+)(?:usize)?, 0x[0-9a-f]+(?:usize)?, 0x[0-9a-f]+(?:usize)?\)']
for f in glob.glob(src + '/**/*.rs', recursive=True):
    for line in open(f, encoding='utf-8'):
        code = line.split('//')[0]
        for p in pats:
            for m in re.findall(p, code):
                offs.add(int(m.replace('_', ''), 16))
code = sorted(o for o in offs if 0x10000 <= o < P.TEXT_END_1304)
data = sorted(o for o in offs if o >= 0x39c8000)
rows, bad = [], []
for o in code:
    n, why = P.find(t4, t5, o)
    print('  %#x -> %s %s' % (o, hex(n) if n is not None else 'NOT FOUND', why))
    (rows if n is not None else bad).append((o, n))
print('code %d found %d not; data %d (+0x1000)' % (len(rows), len(bad), len(data)))
with open(out, 'w', newline='\n') as f:
    f.write('// generated by map_offsets.py (port_13_0_5.py signature match): 13.0.4 main code offset -> 13.0.5\n')
    f.write('pub static CODE_13_0_5: &[(usize, usize)] = &[\n')
    for o, n in rows: f.write('    (%#x, %#x),\n' % (o, n))
    f.write('];\n')
sys.exit(1 if bad else 0)
